<#
.SYNOPSIS
  Apply low-risk fixes from a visual audit report to a copied PPTX.

.DESCRIPTION
  Reads pptx-visual-audit.csv, copies the source PPTX, and fixes only
  deterministic layout issues that do not alter text content: currently this
  means shifting shapes back inside the slide bounds. Blank-slide removal and
  text rewriting are intentionally not performed.

.PARAMETER InputPath
  Source .pptx/.pptm file.

.PARAMETER VisualAuditCsv
  CSV generated by Export-PptxVisualAudit.ps1.

.PARAMETER OutputPath
  New PPTX path to save.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$InputPath,

    [Parameter(Mandatory = $true)]
    [string]$VisualAuditCsv,

    [Parameter(Mandatory = $true)]
    [string]$OutputPath,

    [ValidateRange(0, 40)]
    [double]$MarginPt = 4.0,

    [switch]$IncludeWarnings
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'PhysicsPpt.Common.ps1')
# Picture-fill carriers are detected from the package XML layer; the reader
# lives in the geometry module (Common alone is not enough).
. (Join-Path $PSScriptRoot 'PhysicsPpt.Geometry.ps1')

$script:MsoFalse = 0
$script:MsoGroup = 6
# Shape types whose visible content is carried by a bitmap or an embedding:
# linked picture (4), embedded OLE (7), linked OLE (10), picture (13),
# media (16). A COM position write marks these dirty and PowerPoint re-bakes
# the bitmap on save (Normalize 18.2: 0.6-28% pixel drift on formula shots).
$script:MsoBitmapCarriedTypes = @(4, 7, 10, 13, 16)

function Add-FixRow {
    param(
        [System.Collections.Generic.List[object]]$Rows,
        [string]$File,
        [int]$Slide,
        [string]$Shape,
        [string]$Issue,
        [string]$Status,
        [string]$Details
    )
    $Rows.Add([pscustomobject]@{
        Timestamp = (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
        File = $File
        Slide = $Slide
        Shape = $Shape
        Issue = $Issue
        Status = $Status
        Details = $Details
    }) | Out-Null
}

$InputPath = [System.IO.Path]::GetFullPath($InputPath)
$VisualAuditCsv = [System.IO.Path]::GetFullPath($VisualAuditCsv)
$OutputPath = [System.IO.Path]::GetFullPath($OutputPath)
if ([IO.Path]::GetExtension($InputPath) -notin @('.pptx', '.pptm') -or
    [IO.Path]::GetExtension($InputPath) -ine [IO.Path]::GetExtension($OutputPath)) {
    throw 'OutputPath must retain the source .pptx/.pptm format.'
}
$resultReportPath = Join-Path (Split-Path -Parent $OutputPath) 'pptx-visual-audit-fixes.csv'
if ($OutputPath -ieq $VisualAuditCsv -or $InputPath -ieq $resultReportPath -or $VisualAuditCsv -ieq $resultReportPath) {
    throw 'Output/report paths must not overwrite an input.'
}
if (-not (Test-Path -LiteralPath $InputPath)) { throw "InputPath not found: $InputPath" }
if (-not (Test-Path -LiteralPath $VisualAuditCsv)) { throw "VisualAuditCsv not found: $VisualAuditCsv" }

$outDir = Split-Path -Parent $OutputPath
if (-not (Test-Path -LiteralPath $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }
if ([string]::Equals([System.IO.Path]::GetFullPath($InputPath), $OutputPath, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw "OutputPath must differ from InputPath; the source PPTX is never modified in place."
}

$auditRows = @(Import-Csv -LiteralPath $VisualAuditCsv -Encoding UTF8)
foreach ($row in $auditRows) {
    if ($null -eq $row.PSObject.Properties['FilePath'] -or [string]::IsNullOrWhiteSpace($row.FilePath)) {
        throw 'Visual audit source identity is missing. Re-export the audit before applying fixes.'
    }
}
$rows = @(
    $auditRows |
        Where-Object {
            $(if ($null -ne $_.PSObject.Properties['FilePath'] -and -not [string]::IsNullOrWhiteSpace($_.FilePath)) {
                [IO.Path]::GetFullPath($_.FilePath) -ieq $InputPath
            } else {
                $false
            }) -and
            $_.Issue -eq 'ShapeOutOfSlideBounds' -and
            $_.Shape -ne '(slide)' -and
            ($_.Severity -eq 'Error' -or ($IncludeWarnings -and $_.Severity -eq 'Warning'))
        }
)

$reportRows = New-Object System.Collections.Generic.List[object]
Copy-Item -LiteralPath $InputPath -Destination $OutputPath -Force
# blipFill carriers (formula-screenshot text boxes) are invisible to COM
# Fill.Type (msoFillMixed), so the XML layer is the only dependable signal;
# the working copy carries the same slide XML as the input.
$pictureFillShapeIds = Get-PictureFillShapeIds -SourcePath $OutputPath

$pp = $null
$pres = $null
$presentationFailed = $false
try {
    # Application start and Open reject transiently while a previous
    # automation instance is still tearing down; use the shared COM retry.
    $pp = Invoke-WithComRetry -MaxRetries 3 -DelayMs 1500 -Action { New-PowerPointApplication }
    $pres = Invoke-WithComRetry -MaxRetries 3 -DelayMs 1500 -Action { $pp.Presentations.Open($OutputPath, $script:MsoFalse, $script:MsoFalse, $script:MsoFalse) }
    # PageSetup sits in the same post-open busy window as Open above: one
    # unguarded read here aborts the fix pass before any fix row is reported.
    $slideWidth = [double](Invoke-WithComRetry -MaxRetries 3 -DelayMs 1000 -Action { $pres.PageSetup.SlideWidth })
    $slideHeight = [double](Invoke-WithComRetry -MaxRetries 3 -DelayMs 1000 -Action { $pres.PageSetup.SlideHeight })

    foreach ($row in $rows) {
        $slideNo = [int]$row.Slide
        $shapeName = [string]$row.Shape
        try {
            # Same post-open busy window as the PageSetup reads above: wrap
            # the per-row Item/enumeration reads so a transient rejection is
            # retried instead of consumed as a per-row failure.
            $slide = Invoke-WithComRetry -MaxRetries 3 -DelayMs 1000 -Action { $pres.Slides.Item($slideNo) }
            $shape = $null
            $nameMatches = New-Object System.Collections.Generic.List[object]
            $slideShapes = Invoke-WithComRetry -MaxRetries 3 -DelayMs 1000 -Action { @($slide.Shapes) }.GetNewClosure()
            foreach ($candidate in $slideShapes) {
                if ([string]$candidate.Name -eq $shapeName) {
                    $nameMatches.Add($candidate)
                }
            }
            if ($nameMatches.Count -eq 0) {
                Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'ShapeNotFound' -Details ''
                continue
            }
            if ($nameMatches.Count -gt 1) {
                Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'SkippedAmbiguousName' -Details ("{0} shapes on this slide share the name; refusing to move the wrong one." -f $nameMatches.Count)
                continue
            }
            $shape = $nameMatches[0]
            $shapeType = 0
            try { $shapeType = [int]$shape.Type } catch { }
            if ($shapeType -eq $script:MsoGroup) {
                Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'SkippedGroup' -Details 'Group shapes are skipped by default; moving one would change every child shape position.'
                continue
            }
            if ($shapeType -in $script:MsoBitmapCarriedTypes) {
                Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'SkippedBitmapCarriedType' -Details ("shapeType={0}; moving bitmap-backed shapes would trigger a fill re-bake on save." -f $shapeType)
                continue
            }
            if ($shapeType -eq 14) {
                # msoPlaceholder: the visible content may be a carried bitmap
                # (ContainedType in the same picture/OLE family); moving such
                # a placeholder re-bakes its bitmap on save like any direct
                # bitmap carrier, and the XML blipFill probe only scans p:sp
                # bodies, so this COM-side check is the only guard for it.
                $containedType = 0
                try { $containedType = [int]$shape.PlaceholderFormat.ContainedType } catch { }
                if ($containedType -in $script:MsoBitmapCarriedTypes) {
                    Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'SkippedBitmapCarriedPlaceholder' -Details ("containedType={0}; moving a bitmap-carried placeholder would trigger a fill re-bake on save." -f $containedType)
                    continue
                }
            }
            $shapeId = 0
            try { $shapeId = [int]$shape.Id } catch { }
            if (Test-PictureFillShapeId -Map $pictureFillShapeIds -SlideNumber $slideNo -ShapeId $shapeId) {
                Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'SkippedPictureFillCarrier' -Details 'spPr blipFill carrier (formula-screenshot class); moving it would re-bake the fill bitmap on save.'
                continue
            }

            $oldLeft = [double]$shape.Left
            $oldTop = [double]$shape.Top
            $oldWidth = [double]$shape.Width
            $oldHeight = [double]$shape.Height
            $oldRight = $oldLeft + $oldWidth
            $oldBottom = $oldTop + $oldHeight

            if ($oldWidth -le 0 -or $oldHeight -le 0) {
                Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'SkippedInvalidSize' -Details "width=$oldWidth; height=$oldHeight"
                continue
            }

            $intersectsSlide = ($oldRight -gt 0 -and $oldBottom -gt 0 -and $oldLeft -lt $slideWidth -and $oldTop -lt $slideHeight)
            if (-not $intersectsSlide) {
                Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'SkippedOutsideCanvas' -Details ("left={0:N1}; top={1:N1}; right={2:N1}; bottom={3:N1}; slide={4:N1}x{5:N1}" -f $oldLeft, $oldTop, $oldRight, $oldBottom, $slideWidth, $slideHeight)
                continue
            }

            $targetWidth = $oldWidth
            $targetHeight = $oldHeight
            $maxWidth = [Math]::Max(1, $slideWidth - (2 * $MarginPt))
            $maxHeight = [Math]::Max(1, $slideHeight - (2 * $MarginPt))
            if ($targetWidth -gt $maxWidth -or $targetHeight -gt $maxHeight) {
                Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'SkippedRequiresResize' -Details ("size={0:N1}x{1:N1}; maxSafe={2:N1}x{3:N1}; left={4:N1}; top={5:N1}" -f $oldWidth, $oldHeight, $maxWidth, $maxHeight, $oldLeft, $oldTop)
                continue
            }

            $newLeft = $oldLeft
            $newTop = $oldTop
            if ($newLeft -lt $MarginPt) { $newLeft = $MarginPt }
            if ($newTop -lt $MarginPt) { $newTop = $MarginPt }
            if (($newLeft + $targetWidth) -gt ($slideWidth - $MarginPt)) { $newLeft = $slideWidth - $MarginPt - $targetWidth }
            if (($newTop + $targetHeight) -gt ($slideHeight - $MarginPt)) { $newTop = $slideHeight - $MarginPt - $targetHeight }
            if ($newLeft -lt $MarginPt) { $newLeft = $MarginPt }
            if ($newTop -lt $MarginPt) { $newTop = $MarginPt }

            $shape.Left = [single]$newLeft
            $shape.Top = [single]$newTop

            Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'MovedInsideSlide' -Details ("left {0:N1}->{1:N1}; top {2:N1}->{3:N1}; size {4:N1}x{5:N1}->{6:N1}x{7:N1}" -f $oldLeft, $newLeft, $oldTop, $newTop, $oldWidth, $oldHeight, $targetWidth, $targetHeight)
        } catch {
            Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide $slideNo -Shape $shapeName -Issue 'ShapeOutOfSlideBounds' -Status 'Failed' -Details $_.Exception.Message
        }
    }

    # Same COM retry discipline as every other Save/SaveAs write boundary: a
    # transient rejection here would abort the batch after all fixes applied.
    $saveFormat = if ([IO.Path]::GetExtension($OutputPath) -ieq '.pptm') { 25 } else { 24 }
    Invoke-WithComRetry -Action { $pres.SaveAs($OutputPath, $saveFormat) } | Out-Null
    Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide 0 -Shape '(presentation)' -Issue 'SavedAs' -Status 'Saved' -Details $OutputPath
} catch {
    $presentationFailed = $true
    Add-FixRow -Rows $reportRows -File ([System.IO.Path]::GetFileName($InputPath)) -Slide 0 -Shape '(presentation)' `
        -Issue 'Presentation' -Status 'Failed' -Details $_.Exception.Message
} finally {
    if ($null -ne $pres) {
        try { $pres.Close() | Out-Null } catch { }
        Release-ComObjectSafe -ComObject $pres
    }
    if ($null -ne $pp) {
        try { Stop-PowerPointApplicationIfIdle -Application $pp | Out-Null } catch { }
        Release-ComObjectSafe -ComObject $pp
    }
    [System.GC]::Collect()
    [System.GC]::WaitForPendingFinalizers()
}
if ($presentationFailed -and (Test-Path -LiteralPath $OutputPath)) {
    # Removal happens only after the COM session is fully released above;
    # deleting under the live PowerPoint file lock would silently fail and
    # leave the half-done copy behind.
    try { Remove-Item -LiteralPath $OutputPath -Force -ErrorAction Stop } catch {
        Write-Warning ("Could not remove the incomplete visual-fix copy: {0}" -f $_.Exception.Message)
    }
}

$reportPath = Join-Path $outDir 'pptx-visual-audit-fixes.csv'
Write-Utf8BomCsv -Rows $reportRows.ToArray() -Path $reportPath
if (@($reportRows | Where-Object { $_.Status -eq 'Failed' }).Count -gt 0) {
    throw "Visual fixes failed for one or more shapes; inspect $reportPath"
}

Write-Host "Visual audit fixes done: $OutputPath"
Write-Host "Report saved: $reportPath"
