$docsByPart = @{}
$nssByPart = @{}
$zip = $null
try {
    $zip = [System.IO.Compression.ZipFile]::Open($OutputPath, [System.IO.Compression.ZipArchiveMode]::Update)
    $inventory = Get-OleInventory -Zip $zip -DocsByPart $docsByPart -NssByPart $nssByPart
    $byIndex = @{}
    foreach ($item in $inventory) { $byIndex[[int]$item.Index] = $item }
    $dirtyParts = @{}
    $usedIndexes = @{}

    foreach ($row in $mappingRows) {
        $slideNo = 0
        $null = [int]::TryParse([string]$row.Slide, [ref]$slideNo)
        $name = [string]$row.WhitelistName
        $rowLabel = 'slide {0}; indexes {1}; {2}' -f $slideNo, [string]$row.OleIndex, $name

        if (-not $whitelistNames.ContainsKey($name)) {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleWhitelistRejected' -Details ("whitelist name not in current config: {0}" -f $rowLabel)
            continue
        }
        if (-not $candidateByName.ContainsKey($name)) {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleCandidateMissing' -Details ("no Generated candidate: {0}" -f $rowLabel)
            continue
        }
        $candidate = $candidateByName[$name]
        if ([string]$candidate.TargetSource -ne 'CurrentConfig') {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleWhitelistRejected' -Details ("candidate TargetSource='{0}'; only CurrentConfig candidates may be applied." -f $candidate.TargetSource)
            continue
        }
        $fragmentPath = [string]$candidate.OmmlFragment
        if ([string]::IsNullOrWhiteSpace($fragmentPath) -or -not (Test-Path -LiteralPath $fragmentPath)) {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleFragmentMissing' -Details $fragmentPath
            continue
        }

        $targets = @()
        $ok = $true
        foreach ($piece in @([string]$row.OleIndex -split ';')) {
            $idx = 0
            if (-not [int]::TryParse($piece.Trim(), [ref]$idx)) {
                Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleMappingInvalidIndex' -Details ("'{0}' in {1}" -f $piece, $rowLabel)
                $ok = $false
                break
            }
            if ($usedIndexes.ContainsKey($idx)) {
                Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleIndexReused' -Details ("index {0} already targeted ({1})" -f $idx, $rowLabel)
                $ok = $false
                break
            }
            if (-not $byIndex.ContainsKey($idx)) {
                Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleIndexOutOfRange' -Details ("index {0} not in inventory ({1})" -f $idx, $rowLabel)
                $ok = $false
                break
            }
            $item = $byIndex[$idx]
            if ($item.ProgId -notlike 'Equation*') {
                Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleNotEquationObject' -Details ("index {0} progId='{1}' ({2})" -f $idx, $item.ProgId, $rowLabel)
                $ok = $false
                break
            }
            $null = $usedIndexes.Add($idx, $true)
            $targets += $item
        }
        if (-not $ok) { continue }
        if (@($targets | Where-Object { [int]$_.Slide -ne $slideNo }).Count -gt 0) {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleSlideMismatch' -Details $rowLabel
            continue
        }

        $sizePt = 0
        if (-not [int]::TryParse([string]$row.SizePt, [ref]$sizePt) -or $sizePt -lt 8 -or $sizePt -gt 96) {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleMappingInvalidSize' -Details ("SizePt='{0}' ({1})" -f [string]$row.SizePt, $rowLabel)
            continue
        }
        $mainHex = ([string]$row.MainColorHex).TrimStart('#').ToUpperInvariant()
        $subHex = ([string]$row.SubColorHex).TrimStart('#').ToUpperInvariant()
        if ($mainHex -notmatch '^[0-9A-F]{6}$') {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleMappingInvalidColor' -Details ("MainColorHex='{0}' ({1})" -f $mainHex, $rowLabel)
            continue
        }
        if (-not [string]::IsNullOrWhiteSpace($subHex) -and $subHex -notmatch '^[0-9A-F]{6}$') {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleMappingInvalidColor' -Details ("SubColorHex='{0}' ({1})" -f $subHex, $rowLabel)
            continue
        }
        $accentHex = ''
        if ($null -ne $row.PSObject.Properties['AccentColorHex']) { $accentHex = [string]$row.AccentColorHex }
        $accentHex = $accentHex.TrimStart('#').ToUpperInvariant()
        $accentTokens = if ($null -ne $row.PSObject.Properties['AccentTokens']) { [string]$row.AccentTokens } else { '' }
        if (-not [string]::IsNullOrWhiteSpace($accentHex) -and $accentHex -notmatch '^[0-9A-F]{6}$') {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleMappingInvalidColor' -Details ("AccentColorHex='{0}' ({1})" -f $accentHex, $rowLabel)
            continue
        }
        if (-not [string]::IsNullOrWhiteSpace($accentTokens) -and [string]::IsNullOrWhiteSpace($accentHex)) {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleMappingInvalidColor' -Details ("AccentTokens requires AccentColorHex ({0})" -f $rowLabel)
            continue
        }

        $part = [string]$targets[0].Part
        $doc = $docsByPart[$part]
        $ns = $nssByPart[$part]

        try {
            $fragmentDoc = Convert-OmmlFragmentDocument -FragmentPath $fragmentPath -SizePt $sizePt -MainHex $mainHex -SubHex $subHex -FontName $MathFontName -EastAsianFontName $EastAsianFontName -AccentHex $accentHex -AccentTokens $accentTokens
            # Timing safety: the slide's animation tree references shape spids.
            # Reusing the replaced block's own cNvPr id keeps those references
            # valid (the formula inherits the OLE's animation slot). Multi-target
            # rows would strand the extra ids, so they are refused here.
            $timingSpids = @()
            foreach ($spidNode in @($doc.SelectNodes('//p:timing//p:spTgt', $ns))) {
                $timingSpids += [string]$spidNode.GetAttribute('spid')
            }
            if (@($targets).Count -gt 1) {
                $extraIds = @()
                for ($t = 1; $t -lt @($targets).Count; $t++) {
                    $ownIdNode = $targets[$t].Node.SelectSingleNode('./p:nvGraphicFramePr/p:cNvPr', $ns)
                    if ($null -ne $ownIdNode) { $extraIds += [string]$ownIdNode.GetAttribute('id') }
                }
                if (@($extraIds | Where-Object { $timingSpids -contains $_ }).Count -gt 0) {
                    Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleTimingDangling' -Details ("merged targets carry animated spids ({0}); conversion skipped: {1}" -f ($extraIds -join ','), $rowLabel)
                    continue
                }
            }
            $reuseId = 0
            $ownIdNode = $targets[0].Node.SelectSingleNode('./p:nvGraphicFramePr/p:cNvPr', $ns)
            if ($null -ne $ownIdNode) { $null = [int]::TryParse([string]$ownIdNode.GetAttribute('id'), [ref]$reuseId) }
            $maxId = 0
            foreach ($idNode in @($doc.SelectNodes('//*[@id]', $ns))) {
                $candidateId = 0
                if ([int]::TryParse([string]$idNode.GetAttribute('id'), [ref]$candidateId) -and $candidateId -gt $maxId) { $maxId = $candidateId }
            }
            $finalId = if ($reuseId -gt 0 -and $reuseId -le $maxId) { $reuseId } else { $maxId + 1 }
            $shapeName = 'FormulaOmml {0}' -f $name
            $null = New-OleReplacementAlternateContent -SlideDocument $doc -NamespaceManager $ns -Targets $targets -FragmentDoc $fragmentDoc -ShapeName $shapeName -NewId $finalId
            $dirtyParts[$part] = $true
            $indexLabel = (($targets | ForEach-Object { [string]$_.Index }) -join ';')
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $shapeName -Issue 'OleFormulaReplaced' -Details ("indexes={0}; shapeId={1}; targetUnicodeMath={2}; sizePt={3}; color={4}/{5}; progId={6}" -f $indexLabel, $finalId, $candidate.TargetUnicodeMath, $sizePt, $mainHex, $subHex, [string]$targets[0].ProgId)
        } catch {
            Add-ReportRow -Rows $reportRows -File $inputFileName -Slide $slideNo -Shape $name -Issue 'OleReplaceFailed' -Details ("{0}: {1}" -f $rowLabel, $_.Exception.Message)
        }
    }

    foreach ($part in ($dirtyParts.Keys | Sort-Object)) {
        Write-ZipEntryText -Zip $zip -EntryName $part -Text (Convert-XmlDocumentToString -Document $docsByPart[$part])
    }
} finally {
    if ($null -ne $zip) { $zip.Dispose() }
}

Add-ReportRow -Rows $reportRows -File $inputFileName -Slide 0 -Shape '(presentation)' -Issue 'SavedAs' -Details $OutputPath
Write-Report -Rows $reportRows -Path $ReportPath
Write-Host "Report saved: $ReportPath"
