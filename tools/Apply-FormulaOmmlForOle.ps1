<#
.SYNOPSIS
  Replace reviewed Equation OLE objects with native OfficeMath/OMML shapes in a copied PPTX.

.DESCRIPTION
  Reads a mapping CSV (slide + global OLE index from the formula OLE inventory) and an
  OMML candidates CSV generated by Export-FormulaOmmlCandidates.ps1, copies the source
  PPTX, and swaps each targeted Equation.* OLE graphicFrame for an mc:AlternateContent
  whose Choice is a bounds-preserving text shape carrying the a14:m/m:oMath fragment and
  whose Fallback keeps the original OLE graphicFrame(s) verbatim for older viewers.
  Run properties are restyled to the deck's native math convention (m:nor, role-based
  italic posture, configured fonts, main/subscript colors, explicit size). The source PPTX
  is never modified.

.PARAMETER InputPath
  Source .pptx file.

.PARAMETER MappingCsv
  CSV with columns: Slide,OleIndex,WhitelistName,SizePt,MainColorHex,SubColorHex,Note.
  OleIndex is the global zero-based OLE index from the inventory ordering
  (slide ascending, then y, then x); use semicolons to merge OLEs into one formula.

.PARAMETER OmmlCandidateCsv
  formula-omml-candidates.csv generated by Export-FormulaOmmlCandidates.ps1.

.PARAMETER OutputPath
  New PPTX path to save.

.PARAMETER ReportPath
  CSV report path. Defaults next to OutputPath.

.PARAMETER MathFontName
  Latin/math font applied to formula runs. Defaults to Cambria Math.

.PARAMETER EastAsianFontName
  East Asian font applied to Chinese formula runs and subscripts. Defaults to 微软雅黑.

.PARAMETER MaxItems
  Maximum mapping rows to apply in one run. Defaults to 20.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$InputPath,

    [Parameter(Mandatory = $true)]
    [string]$MappingCsv,

    [Parameter(Mandatory = $true)]
    [string]$OmmlCandidateCsv,

    [Parameter(Mandatory = $true)]
    [string]$OutputPath,

    [string]$ReportPath,

    [string]$MathFontName = 'Cambria Math',

    [string]$EastAsianFontName = '',

    [ValidateRange(1, 100)]
    [int]$MaxItems = 20
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'PhysicsPpt.Common.ps1')

if ([string]::IsNullOrWhiteSpace($EastAsianFontName)) {
    $styleConfigPath = Join-Path (Split-Path -Parent $PSScriptRoot) 'config\physics-ppt-style.config.json'
    if (Test-Path -LiteralPath $styleConfigPath) {
        try {
            $styleConfig = Get-Content -LiteralPath $styleConfigPath -Raw -Encoding UTF8 | ConvertFrom-Json
            if ($null -ne $styleConfig.fonts.mathEastAsian -and -not [string]::IsNullOrWhiteSpace([string]$styleConfig.fonts.mathEastAsian)) {
                $EastAsianFontName = [string]$styleConfig.fonts.mathEastAsian
            }
        } catch {
            throw "Formula style config could not be loaded: $($_.Exception.Message)"
        }
    }
}
if ([string]::IsNullOrWhiteSpace($EastAsianFontName)) { $EastAsianFontName = '宋体' }

