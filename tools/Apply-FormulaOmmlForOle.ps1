function Write-Report {
    param($Rows, [string]$Path)
    $parent = Split-Path -Parent $Path
    if (-not [string]::IsNullOrWhiteSpace($parent) -and -not (Test-Path -LiteralPath $parent)) {
        New-Item -ItemType Directory -Path $parent -Force | Out-Null
    }
    $utf8Bom = New-Object System.Text.UTF8Encoding($true)
    $csvLines = @($Rows | ConvertTo-Csv -NoTypeInformation | ForEach-Object { [string]$_ })
    [System.IO.File]::WriteAllLines($Path, $csvLines, $utf8Bom)
}

function Write-ZipEntryText {
    param($Zip, [string]$EntryName, [string]$Text)
    $entry = $Zip.GetEntry($EntryName)
    if ($null -eq $entry) { throw "Zip entry not found: $EntryName" }
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    $bytes = $utf8NoBom.GetBytes($Text)
    $entry.Delete() | Out-Null
    $newEntry = $Zip.CreateEntry($EntryName)
    $stream = $newEntry.Open()
    try {
        $stream.Write($bytes, 0, $bytes.Length)
    } finally {
        $stream.Dispose()
    }
}

function New-NamespaceManager {
    param([System.Xml.XmlDocument]$Document)
    $ns = New-Object System.Xml.XmlNamespaceManager($Document.NameTable)
    $ns.AddNamespace('a', $script:NsA)
    $ns.AddNamespace('a14', $script:NsA14)
    $ns.AddNamespace('m', $script:NsM)
    $ns.AddNamespace('p', $script:NsP)
    $ns.AddNamespace('mc', $script:NsMc)
    # Comma guards against PowerShell unrolling the IEnumerable manager into NameTable strings.
    return ,$ns
}

function Get-SlidePartNameMap {
    param($Zip)
    $presEntry = $Zip.GetEntry('ppt/presentation.xml')
    if ($null -eq $presEntry) { throw 'ppt/presentation.xml missing' }
    $reader = New-Object System.IO.StreamReader($presEntry.Open(), [System.Text.Encoding]::UTF8)
    $presText = $reader.ReadToEnd()
    $reader.Dispose()
    $relsEntry = $Zip.GetEntry('ppt/_rels/presentation.xml.rels')
    $reader = New-Object System.IO.StreamReader($relsEntry.Open(), [System.Text.Encoding]::UTF8)
    $relsText = $reader.ReadToEnd()
    $reader.Dispose()
    $ridToPart = @{}
    foreach ($match in [regex]::Matches($relsText, 'Id="(rId\d+)"[^>]*Target="(slides/slide\d+\.xml)"')) {
        $ridToPart[$match.Groups[1].Value] = 'ppt/' + $match.Groups[2].Value
    }
    $map = @{}
    $order = 0
    foreach ($match in [regex]::Matches($presText, '<p:sldId[^>]*r:id="(rId\d+)"')) {
        $order++
        $rid = $match.Groups[1].Value
        if ($ridToPart.ContainsKey($rid)) { $map[$order] = $ridToPart[$rid] }
    }
    return $map
}

function Test-IsProtectedScopeNode {
    # Shapes inside groups (invariant: groups are never modified) and inside
    # mc:Fallback branches must never become replacement targets.
    param([System.Xml.XmlElement]$Node)
    $ancestor = $Node.ParentNode
    while ($null -ne $ancestor) {
        if ($ancestor.LocalName -eq 'grpSp' -or $ancestor.LocalName -eq 'Fallback') { return $true }
        $ancestor = $ancestor.ParentNode
    }
    return $false
}

function Get-OleInventory {
    # Deterministic global OLE ordering: presentation-order slide ascending,
    # then y, then x. Must stay in sync with the inventory that produced the
    # mapping CSV (Export-FormulaOleInventory ordering).
    param($Zip, [hashtable]$DocsByPart, [hashtable]$NssByPart)
    $slidePartMap = Get-SlidePartNameMap -Zip $Zip
    $inventory = New-Object System.Collections.Generic.List[object]
    foreach ($slideNo in ($slidePartMap.Keys | Sort-Object)) {
        $entryName = [string]$slidePartMap[$slideNo]
        $doc = New-Object System.Xml.XmlDocument
        $doc.PreserveWhitespace = $true
        $doc.LoadXml((Read-ZipEntryText -Zip $Zip -EntryName $entryName))
        $ns = New-NamespaceManager -Document $doc
        $DocsByPart[$entryName] = $doc
        $NssByPart[$entryName] = $ns
        # Target OLE blocks at spTree level only. PowerPoint 2016+ stores each
        # equation OLE as a top-level mc:AlternateContent (graphicFrame lives in
        # a branch); older files may expose a bare graphicFrame. Anything deeper
        # (inside graphicData/Fallback) is not a block boundary and must never
        # receive a replacement.
        foreach ($spTree in @($doc.SelectNodes('//p:spTree', $ns))) {
            foreach ($child in @($spTree.ChildNodes)) {
                if ($child.NodeType -ne [System.Xml.XmlNodeType]::Element) { continue }
                $isBlock = ($child.LocalName -eq 'AlternateContent' -or $child.LocalName -eq 'graphicFrame')
                if (-not $isBlock) { continue }
                if (Test-IsProtectedScopeNode -Node $child) { continue }
                if ($null -ne $child.SelectSingleNode('.//p:cNvPr[contains(@name, "FormulaOmml")]', $ns)) { continue }
                $oleObj = $child.SelectSingleNode('.//p:oleObj', $ns)
                if ($null -eq $oleObj) { continue }
                $xfrm = $child.SelectSingleNode('.//p:xfrm', $ns)
                if ($null -eq $xfrm) { continue }
                $off = $xfrm.SelectSingleNode('./a:off', $ns)
                $ext = $xfrm.SelectSingleNode('./a:ext', $ns)
                if ($null -eq $off -or $null -eq $ext) { continue }
                $inventory.Add([pscustomobject]@{
                    Slide = [int]$slideNo
                    Part = $entryName
                    Node = $child
                    ProgId = [string]$oleObj.GetAttribute('progId')
                    X = [int64]$off.GetAttribute('x')
                    Y = [int64]$off.GetAttribute('y')
                    Cx = [int64]$ext.GetAttribute('cx')
                    Cy = [int64]$ext.GetAttribute('cy')
                }) | Out-Null
            }
        }
    }
    $sorted = @($inventory | Sort-Object -Property Slide, Y, X)
    for ($i = 0; $i -lt $sorted.Count; $i++) { $sorted[$i] | Add-Member -NotePropertyName Index -NotePropertyValue $i -Force }
    return $sorted
}

function Get-OmmlRunRole {
    param([string]$Text)
    if ([string]$Text -cmatch '^[0-9]+(?:\.[0-9]+)?$') { return 'Number' }
    if ([string]$Text -cmatch '^[\u3400-\u9FFF]$') { return 'Chinese' }
    if ([string]$Text -cmatch '^[A-Za-z]+$' -or [string]$Text -cmatch '^[\u0370-\u03FF]$') {
        if ([string]$Text -in @('J', 'kg', 'Pa', 'N', 'W', 'Hz', '℃')) { return 'Unit' }
        return 'Variable'
    }
    if ([string]$Text -in @('+', '-', '−', '×', '⋅', '∙', '*', '=', ',', '.', '(', ')', '<', '>', '≤', '≥')) { return 'Operator' }
    return 'Text'
}

function Convert-OmmlFragmentDocument {
    # Restyle an exporter fragment to the deck-native math convention.  The
    # source MathType formulas use a heavy display style, but only variables
    # are italic; operators, numbers, units, and Chinese subscripts stay
    # upright.  Chinese subscripts are reduced so they do not overflow the
    # original OLE bounds when PowerPoint renders the OMML text shape.
    param(
        [string]$FragmentPath,
        [int]$SizePt,
        [string]$MainHex,
        [string]$SubHex,
        [string]$FontName,
        [string]$EastAsianFontName,
        [string]$AccentHex,
        [string]$AccentTokens
    )
    $frag = New-Object System.Xml.XmlDocument
    $frag.PreserveWhitespace = $false
    $frag.Load($FragmentPath)
    $ns = New-NamespaceManager -Document $frag

    foreach ($run in @($frag.SelectNodes('//m:r', $ns))) {
        $mRPr = $run.SelectSingleNode('./m:rPr', $ns)
        if ($null -eq $mRPr) {
            $mRPr = $frag.CreateElement('m', 'rPr', $script:NsM)
            $null = $run.PrependChild($mRPr)
        }
        if ($null -eq $mRPr.SelectSingleNode('./m:nor', $ns)) {
            $nor = $frag.CreateElement('m', 'nor', $script:NsM)
            $null = $mRPr.PrependChild($nor)
        }
        $aRPr = $run.SelectSingleNode('./a:rPr', $ns)
        if ($null -eq $aRPr) {
            $aRPr = $frag.CreateElement('a', 'rPr', $script:NsA)
            $null = $run.InsertAfter($aRPr, $mRPr)
        }
        $runTextNode = $run.SelectSingleNode('./m:t', $ns)
        $runText = if ($null -ne $runTextNode) { [string]$runTextNode.InnerText } else { '' }
        $role = Get-OmmlRunRole -Text $runText

        $isSubscript = $false
        $ancestor = $run.ParentNode
        while ($null -ne $ancestor -and $ancestor.NodeType -ne [System.Xml.XmlNodeType]::Document) {
            if ($ancestor.LocalName -eq 'sub' -and $ancestor.NamespaceURI -eq $script:NsM) { $isSubscript = $true; break }
            $ancestor = $ancestor.ParentNode
        }

        $aRPr.SetAttribute('lang', $(if ($role -in @('Chinese', 'Text')) { 'zh-CN' } else { 'en-US' }))
        $aRPr.SetAttribute('altLang', $(if ($role -in @('Chinese', 'Text')) { 'en-US' } else { 'zh-CN' }))
        $runSize = $SizePt * 100
        if ($isSubscript) { $runSize = [Math]::Max(800, [int][Math]::Round($runSize * 0.72)) }
        $aRPr.SetAttribute('sz', ([string]$runSize))
        # MathType's Chinese subscripts and operators are upright regular glyphs;
        # forcing every OMML run bold makes the replacement wider than the
        # original OLE tight box (especially Q_放 / Q_吸). Keep the variable
        # posture role-based, but preserve regular weight for every run.
        $aRPr.SetAttribute('b', '0')
        $aRPr.SetAttribute('i', $(if ($role -eq 'Variable') { '1' } else { '0' }))

        $hex = $MainHex
        if ($isSubscript -and -not [string]::IsNullOrWhiteSpace($SubHex)) {
            $hex = $SubHex
        } elseif (-not [string]::IsNullOrWhiteSpace($AccentHex) -and
            @($AccentTokens -split ';' | ForEach-Object { $_.Trim() } | Where-Object { $_ -ne '' }) -contains $runText) {
            $hex = $AccentHex
        }

        $oldFill = $aRPr.SelectSingleNode('./a:solidFill', $ns)
        if ($null -ne $oldFill) { $null = $aRPr.RemoveChild($oldFill) }
        $fill = $frag.CreateElement('a', 'solidFill', $script:NsA)
        $clr = $frag.CreateElement('a', 'srgbClr', $script:NsA)
        $clr.SetAttribute('val', $hex)
        $null = $fill.AppendChild($clr)
        $latin = $aRPr.SelectSingleNode('./a:latin', $ns)
        if ($null -ne $latin) {
            $null = $aRPr.InsertBefore($fill, $latin)
        } else {
            $null = $aRPr.AppendChild($fill)
            $latin = $frag.CreateElement('a', 'latin', $script:NsA)
            $null = $aRPr.AppendChild($latin)
        }
        $latin.SetAttribute('typeface', $FontName)
        $ea = $aRPr.SelectSingleNode('./a:ea', $ns)
        if ($null -eq $ea) {
            $ea = $frag.CreateElement('a', 'ea', $script:NsA)
            $null = $aRPr.InsertAfter($ea, $latin)
        }
        $ea.SetAttribute('typeface', $EastAsianFontName)
    }

    # Fraction bars and other structure take their color/size from m:ctrlPr/a:rPr.
    foreach ($ctrlPr in @($frag.SelectNodes('//m:ctrlPr', $ns))) {
        $ctrlRPr = $ctrlPr.SelectSingleNode('./a:rPr', $ns)
        if ($null -eq $ctrlRPr) {
            $ctrlRPr = $frag.CreateElement('a', 'rPr', $script:NsA)
            $null = $ctrlPr.AppendChild($ctrlRPr)
        }
        $ctrlRPr.SetAttribute('lang', 'en-US')
        $ctrlRPr.SetAttribute('altLang', 'zh-CN')
        $ctrlRPr.SetAttribute('sz', ([string]($SizePt * 100)))
        $ctrlRPr.SetAttribute('b', '0')
        $ctrlRPr.SetAttribute('i', '0')
        $oldFill = $ctrlRPr.SelectSingleNode('./a:solidFill', $ns)
        if ($null -ne $oldFill) { $null = $ctrlRPr.RemoveChild($oldFill) }
        $fill = $frag.CreateElement('a', 'solidFill', $script:NsA)
        $clr = $frag.CreateElement('a', 'srgbClr', $script:NsA)
        $clr.SetAttribute('val', $MainHex)
        $null = $fill.AppendChild($clr)
        # CT_TextCharacterProperties sequence: fill must precede latin/ea.
        $ctrlLatin = $ctrlRPr.SelectSingleNode('./a:latin', $ns)
        if ($null -ne $ctrlLatin) {
            $null = $ctrlRPr.InsertBefore($fill, $ctrlLatin)
        } else {
            $null = $ctrlRPr.AppendChild($fill)
        }
        $ctrlLatin = $ctrlRPr.SelectSingleNode('./a:latin', $ns)
        if ($null -eq $ctrlLatin) {
            $ctrlLatin = $frag.CreateElement('a', 'latin', $script:NsA)
            $null = $ctrlRPr.AppendChild($ctrlLatin)
        }
        $ctrlLatin.SetAttribute('typeface', $FontName)
        $ctrlEa = $ctrlRPr.SelectSingleNode('./a:ea', $ns)
        if ($null -eq $ctrlEa) {
            $ctrlEa = $frag.CreateElement('a', 'ea', $script:NsA)
            $null = $ctrlRPr.AppendChild($ctrlEa)
        }
        $ctrlEa.SetAttribute('typeface', $EastAsianFontName)
    }
    # XmlDocument is IEnumerable too; the comma keeps the document intact.
    return ,$frag
}

function New-OleReplacementAlternateContent {
    # Choice = bounds-preserving text shape with the OMML fragment;
    # Fallback = the original OLE graphicFrame(s), byte-identical clones.
    param(
        [System.Xml.XmlDocument]$SlideDocument,
        [System.Xml.XmlNamespaceManager]$NamespaceManager,
        $Targets,
        [System.Xml.XmlDocument]$FragmentDoc,
        [string]$ShapeName,
        [int]$NewId
    )
    $minX = [int64]::MaxValue; $minY = [int64]::MaxValue
    $maxX = [int64]::MinValue; $maxY = [int64]::MinValue
    foreach ($target in $Targets) {
        if ([int64]$target.X -lt $minX) { $minX = [int64]$target.X }
        if ([int64]$target.Y -lt $minY) { $minY = [int64]$target.Y }
        if ([int64]($target.X + $target.Cx) -gt $maxX) { $maxX = [int64]($target.X + $target.Cx) }
        if ([int64]($target.Y + $target.Cy) -gt $maxY) { $maxY = [int64]($target.Y + $target.Cy) }
    }

    $alternate = $SlideDocument.CreateElement('mc', 'AlternateContent', $script:NsMc)
    $null = $alternate.SetAttribute('xmlns:a14', $script:NsA14)
    $choice = $SlideDocument.CreateElement('mc', 'Choice', $script:NsMc)
    $null = $choice.SetAttribute('Requires', 'a14')

    $sp = $SlideDocument.CreateElement('p', 'sp', $script:NsP)
    $nvSpPr = $SlideDocument.CreateElement('p', 'nvSpPr', $script:NsP)
    $cNvPr = $SlideDocument.CreateElement('p', 'cNvPr', $script:NsP)
    $null = $cNvPr.SetAttribute('id', ([string]$NewId))
    $null = $cNvPr.SetAttribute('name', $ShapeName)
    $null = $nvSpPr.AppendChild($cNvPr)
    $null = $nvSpPr.AppendChild($SlideDocument.CreateElement('p', 'cNvSpPr', $script:NsP))
    $null = $nvSpPr.AppendChild($SlideDocument.CreateElement('p', 'nvPr', $script:NsP))
    $null = $sp.AppendChild($nvSpPr)

    $spPr = $SlideDocument.CreateElement('p', 'spPr', $script:NsP)
    $xfrm = $SlideDocument.CreateElement('a', 'xfrm', $script:NsA)
    $off = $SlideDocument.CreateElement('a', 'off', $script:NsA)
    $null = $off.SetAttribute('x', ([string]$minX))
    $null = $off.SetAttribute('y', ([string]$minY))
    $ext = $SlideDocument.CreateElement('a', 'ext', $script:NsA)
    $null = $ext.SetAttribute('cx', ([string]($maxX - $minX)))
    $null = $ext.SetAttribute('cy', ([string]($maxY - $minY)))
    $null = $xfrm.AppendChild($off)
    $null = $xfrm.AppendChild($ext)
    $null = $spPr.AppendChild($xfrm)
    $prstGeom = $SlideDocument.CreateElement('a', 'prstGeom', $script:NsA)
    $null = $prstGeom.SetAttribute('prst', 'rect')
    $null = $prstGeom.AppendChild($SlideDocument.CreateElement('a', 'avLst', $script:NsA))
    $null = $spPr.AppendChild($prstGeom)
    $null = $spPr.AppendChild($SlideDocument.CreateElement('a', 'noFill', $script:NsA))
    $ln = $SlideDocument.CreateElement('a', 'ln', $script:NsA)
    $null = $ln.AppendChild($SlideDocument.CreateElement('a', 'noFill', $script:NsA))
    $null = $spPr.AppendChild($ln)
    $null = $sp.AppendChild($spPr)

    $txBody = $SlideDocument.CreateElement('p', 'txBody', $script:NsP)
    $bodyPr = $SlideDocument.CreateElement('a', 'bodyPr', $script:NsA)
    $null = $bodyPr.SetAttribute('wrap', 'square')
    $null = $bodyPr.SetAttribute('lIns', '0')
    $null = $bodyPr.SetAttribute('tIns', '0')
    $null = $bodyPr.SetAttribute('rIns', '0')
    $null = $bodyPr.SetAttribute('bIns', '0')
    $null = $bodyPr.SetAttribute('anchor', 'ctr')
    $null = $bodyPr.SetAttribute('rtlCol', '0')
    # Native OMML glyph metrics can be a few percent wider than the original
    # MathType OLE bitmap. Normal autofit keeps the original tight box and
    # applies only the minimum shrink needed for a converted segment.
    $null = $bodyPr.AppendChild($SlideDocument.CreateElement('a', 'normAutofit', $script:NsA))
    $null = $txBody.AppendChild($bodyPr)
    $null = $txBody.AppendChild($SlideDocument.CreateElement('a', 'lstStyle', $script:NsA))
    $para = $SlideDocument.CreateElement('a', 'p', $script:NsA)
    $pPr = $SlideDocument.CreateElement('a', 'pPr', $script:NsA)
    $null = $pPr.SetAttribute('algn', 'ctr')
    $null = $para.AppendChild($pPr)
    $null = $para.AppendChild($SlideDocument.ImportNode($FragmentDoc.DocumentElement, $true))
    $null = $txBody.AppendChild($para)
    $null = $sp.AppendChild($txBody)
    $null = $choice.AppendChild($sp)
    $null = $alternate.AppendChild($choice)

    $fallback = $SlideDocument.CreateElement('mc', 'Fallback', $script:NsMc)
    foreach ($target in $Targets) {
        $null = $fallback.AppendChild($target.Node.CloneNode($true))
    }
    $null = $alternate.AppendChild($fallback)

    $parent = $Targets[0].Node.ParentNode
    $null = $parent.ReplaceChild($alternate, $Targets[0].Node)
    for ($i = 1; $i -lt $Targets.Count; $i++) {
        $null = $parent.RemoveChild($Targets[$i].Node)
    }
    return $alternate
}

function Convert-XmlDocumentToString {
    param([System.Xml.XmlDocument]$Document)
    $settings = New-Object System.Xml.XmlWriterSettings
    $settings.Indent = $true
    $settings.OmitXmlDeclaration = $true
    $builder = New-Object System.Text.StringBuilder
    $writer = [System.Xml.XmlWriter]::Create($builder, $settings)
    try {
        $Document.Save($writer)
    } finally {
        if ($null -ne $writer) { $writer.Dispose() }
    }
    return $builder.ToString()
}

