$mappingRows = @(Import-Csv -LiteralPath $MappingCsv -Encoding UTF8 | Select-Object -First $MaxItems)

$reportRows = New-Object System.Collections.Generic.List[object]
$inputFileName = [System.IO.Path]::GetFileName($InputPath)
