<#
.SYNOPSIS
  Export editable formula candidates as MathML and OfficeMath/OMML XML fragments.

.DESCRIPTION
  Reads formula-review.csv and converts whitelist rows with
  SuggestedAction=ReviewWhitelistConversion into reviewable XML fragments.
  This tool does not modify PPTX files. It is the safe handoff between
  formula review and a future PPTX OfficeMath writer.

.PARAMETER FormulaReviewCsv
  formula-review.csv generated by Invoke-PhysicsPptWorkflow.ps1.

.PARAMETER OutputDir
  Directory where CSV, JSON, MathML, and OMML fragments are written.

.PARAMETER MaxItems
  Maximum whitelist rows to export in one run.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$FormulaReviewCsv,

    [Parameter(Mandatory = $true)]
    [string]$OutputDir,

    [ValidateRange(1, 1000)]
    [int]$MaxItems = 100
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

. (Join-Path $PSScriptRoot 'PhysicsPpt.Common.ps1')

. (Join-Path $PSScriptRoot 'PhysicsPpt.Formula.ps1')

$FormulaReviewCsv = [System.IO.Path]::GetFullPath($FormulaReviewCsv)
$OutputDir = [System.IO.Path]::GetFullPath($OutputDir)
if (-not (Test-Path -LiteralPath $FormulaReviewCsv)) { throw "FormulaReviewCsv not found: $FormulaReviewCsv" }
if (-not (Test-Path -LiteralPath $OutputDir)) { New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null }

$fragmentDir = Join-Path $OutputDir 'fragments'
if (-not (Test-Path -LiteralPath $fragmentDir)) { New-Item -ItemType Directory -Path $fragmentDir -Force | Out-Null }
$formulaIrDir = Join-Path $OutputDir 'formula-ir'
if (-not (Test-Path -LiteralPath $formulaIrDir)) { New-Item -ItemType Directory -Path $formulaIrDir -Force | Out-Null }

$reviewRows = @(
    Import-Csv -LiteralPath $FormulaReviewCsv -Encoding UTF8 |
        Where-Object { $_.SuggestedAction -eq 'ReviewWhitelistConversion' -and -not [string]::IsNullOrWhiteSpace($_.WhitelistCandidate) } |
        Select-Object -First $MaxItems
)

$results = New-Object System.Collections.Generic.List[object]
for ($i = 0; $i -lt $reviewRows.Count; $i++) {
    $row = $reviewRows[$i]
    if ($null -eq $row.PSObject.Properties['Slide'] -or [string]$row.Slide -notmatch '^\d+$') {
        Write-Warning "Skipping candidate row with invalid Slide value: '$($row.Slide)' ($($row.File))"
        continue
    }
    $name = Get-FormulaDetailValue -Details ([string]$row.WhitelistCandidate) -Key 'name'
    $targetUnicodeMath = Get-FormulaDetailValue -Details ([string]$row.WhitelistCandidate) -Key 'targetUnicodeMath'
    $targetTex = Get-FormulaDetailValue -Details ([string]$row.WhitelistCandidate) -Key 'targetTex'
    $currentRule = Get-CurrentWhitelistRule -FormulaText ([string]$row.FormulaText)
    if ($null -ne $currentRule) {
        $name = Get-FormulaRuleValue -Rule $currentRule -Name 'name' -Default $name
        $targetUnicodeMath = Get-FormulaRuleValue -Rule $currentRule -Name 'targetUnicodeMath' -Default $targetUnicodeMath
        $targetTex = Get-FormulaRuleValue -Rule $currentRule -Name 'targetTex' -Default $targetTex
    }
    $fileStem = if ($null -ne $row.PSObject.Properties['FileRelativePath'] -and -not [string]::IsNullOrWhiteSpace([string]$row.FileRelativePath)) {
        Convert-ToSafeFormulaPathSegment -Name ([string]$row.FileRelativePath -replace '[\\/]', '__')
    } elseif ($null -ne $row.PSObject.Properties['FilePath'] -and -not [string]::IsNullOrWhiteSpace([string]$row.FilePath)) {
        Convert-ToSafeFormulaPathSegment -Name ([System.IO.Path]::GetFileNameWithoutExtension([string]$row.FilePath))
    } else {
        Convert-ToSafeFormulaPathSegment -Name ([string]$row.File)
    }
    $baseName = '{0:000}_{1}_slide-{2:000}_{3}_{4}' -f ($i + 1), $fileStem, ([int]$row.Slide), (Convert-ToSafeFormulaPathSegment -Name ([string]$row.Shape)), (Convert-ToSafeFormulaPathSegment -Name $name)
    $ommlPath = Join-Path $fragmentDir ($baseName + '.omml.xml')
    $mathMlPath = Join-Path $fragmentDir ($baseName + '.mathml.xml')
    $formulaIrPath = Join-Path $formulaIrDir ($baseName + '.json')

    $status = 'Generated'
    $message = ''
    $formulaIrStatus = 'Unresolved'
    $tokensJson = '[]'
    try {
        if ([string]::IsNullOrWhiteSpace($targetUnicodeMath)) {
            throw 'WhitelistCandidate does not contain targetUnicodeMath.'
        }
        $ast = Parse-FormulaAst -UnicodeMath $targetUnicodeMath
        $tokens = Convert-AstToFormulaIrToken -Node $ast
        $tokensJson = $tokens | ConvertTo-Json -Depth 20 -Compress
        $formulaIrStatus = 'Resolved'
        $canonicalUnicodeMath = Convert-AstToUnicodeMath -Node $ast
        $canonicalTex = Convert-AstToCanonicalTex -Node $ast
        $ommlDoc = New-OmmlFragment -UnicodeMath $canonicalUnicodeMath
        $mathMlDoc = New-MathMlFragment -UnicodeMath $canonicalUnicodeMath
        Write-Utf8BomText -Path $ommlPath -Text (Convert-XmlDocumentToString -Document $ommlDoc)
        Write-Utf8BomText -Path $mathMlPath -Text (Convert-XmlDocumentToString -Document $mathMlDoc)
        $formulaIr = [ordered]@{
            schemaVersion = 1
            candidateVersion = 1
            source = [ordered]@{ file = [string]$row.File; filePath = [string]$row.FilePath; slide = [int]$row.Slide; shape = [string]$row.Shape; sourceText = [string]$row.FormulaText }
            recognition = [ordered]@{ method = 'Whitelist'; status = 'Resolved'; rawCandidate = [string]$row.FormulaText }
            canonical = [ordered]@{ status = $formulaIrStatus; source = 'CurrentConfig'; formulaName = $name; unicodeMath = $canonicalUnicodeMath; tex = $canonicalTex; sourceUnicodeMath = $targetUnicodeMath; sourceTex = $targetTex; mathmlPath = $mathMlPath; tokens = $tokens }
            target = [ordered]@{ ommlPath = $ommlPath; styleProfile = 'physics-default' }
            decision = [ordered]@{ status = 'CandidateOnly'; writeBackAllowed = $false; reason = 'Candidate fragment only; a separate explicit writer and gates are required.' }
        }
        Write-Utf8BomText -Path $formulaIrPath -Text ($formulaIr | ConvertTo-Json -Depth 30)
    } catch {
        $status = 'Failed'
        $message = $_.Exception.Message
        $ommlPath = ''
        $mathMlPath = ''
        $formulaIrPath = ''
        $formulaIrStatus = 'Unsupported'
    }

    $results.Add([pscustomobject]@{
        File = $row.File
        FilePath = if ($null -ne $row.PSObject.Properties['FilePath']) { [string]$row.FilePath } else { [string]$row.File }
        Slide = $row.Slide
        Shape = $row.Shape
        FormulaText = $row.FormulaText
        Name = $name
        TargetUnicodeMath = $targetUnicodeMath
        TargetTex = $targetTex
        FormulaIrStatus = $formulaIrStatus
        TokensJson = $tokensJson
        TargetSource = if ($null -ne $currentRule) { 'CurrentConfig' } else { 'FormulaReviewCsv' }
        OmmlFragment = $ommlPath
        MathMlFragment = $mathMlPath
        FormulaIrFragment = $formulaIrPath
        Status = $status
        Message = $message
    }) | Out-Null
}

$csvPath = Join-Path $OutputDir 'formula-omml-candidates.csv'
$jsonPath = Join-Path $OutputDir 'formula-omml-candidates.json'
$manifestPath = Join-Path $OutputDir 'formula-omml-candidates-manifest.json'

Write-Utf8BomCsv -InputObject $results.ToArray() -Path $csvPath
$results | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $jsonPath -Encoding UTF8

$manifest = [pscustomobject]@{
    generatedAt = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
    formulaReviewCsv = $FormulaReviewCsv
    outputDir = $OutputDir
    fragmentDir = $fragmentDir
    formulaIrDir = $formulaIrDir
    candidateCount = $reviewRows.Count
    generatedCount = @($results | Where-Object { $_.Status -eq 'Generated' }).Count
    failedCount = @($results | Where-Object { $_.Status -ne 'Generated' }).Count
    formulaIrResolvedCount = @($results | Where-Object { $_.FormulaIrStatus -eq 'Resolved' }).Count
    csv = $csvPath
    json = $jsonPath
    note = 'Fragments are review artifacts. They are not inserted into PPTX by this tool.'
}
$manifest | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $manifestPath -Encoding UTF8

Write-Host "OMML candidate export done: $OutputDir"
Write-Host "Generated: $($manifest.generatedCount) / Candidates: $($manifest.candidateCount)"
